"""评论里的品牌词提及率 —— 水军的 SEO / 品牌考核痕迹。

直觉
----
真人聊产品会**省字**：说「珂润」「那个面霜」「这个水」。
派单水军的 KPI 是**品牌词出现次数**（SEO 权重 + 品牌方验收），
所以会写全称 + 型号：「雅诗兰黛小棕瓶精华真的绝了」。

所以看的是：评论里出现**本篇品牌/产品词**的比例。
词表 = 本篇 tags ∪ {跨语料词池里出现在本篇标题/正文的词}。

⚠️ 与 ``tag_count`` 的分工（两个都保留）
--------------------------------------
==================  ==========================  ========================
                    ``tag_count``               ``brand_mention_ratio``
==================  ==========================  ========================
看哪儿              **笔记正文的话题标签**      **评论正文**
测什么              SEO 堆砌（作者侧）          品牌词渗透（评论侧）
==================  ==========================  ========================

一个是作者在给自己贴标签，一个是评论者在念品牌名 —— 两回事。

实测（2026-10-11，40 篇标注里 37 篇可算，high 6 篇）
--------------------------------------------------
======================  ======  =======
词表来源                覆盖    AUC
======================  ======  =======
只用本篇 tags           30/40   0.583
tags ∪ 词池 ∩ 本篇正文  **37/40**  **0.589**
======================  ======  =======
选后者：AUC 基本持平（0.583→0.589 在噪声内），但**覆盖率 30→37**。
覆盖为什么重要：43 篇里有 7 篇的 tags 解析失败（只剩假标签「笔记」），
只用 tags 会让那些篇直接报 missing。

试过但**没采用**的改动
----------------------
**品类词停用表**（面霜/精华/护肤/修护…）。直觉上这些泛词该滤掉，
实测却**降低** AUC：0.583 → 0.523（只用 tags）、0.589 → 0.543（加词池）。
说明品类词也带信号 —— 水军写「这个面霜真的很好用」，
真人写「我用了三个月皮肤稳定了」（根本没提产品）。
所以本信号实际测的是「**评论有多产品导向**」，
不只是「有没有念品牌名」。停用表已删除，不要加回来。

风险方向
--------
**提及率越高越可疑**。

阈值依据（扫过，不是拍的）
--------------------------
实测占比分布：min 0.000 · p25 0.118 · 中位 0.200 · p75 0.438 · max 0.833。

第一版我写了 ``_LO=0.05 / _HI=0.30``，但 ``_HI`` 低于 p75 ——
大半篇都被压成同一个值（0.6），区分度直接归零（AUC 0.589 → 0.578）。
**和 ``publish_burst`` 犯的是同一个错。**

扫描结果：

=================  ======
_HI（_LO=0）        AUC
=================  ======
0.30               0.578  ← 第一版
0.50               0.581
**0.70**           **0.591**
0.85               0.589
=================  ======

``_LO`` 扫 0.00/0.05/0.15/0.25/0.35 得 0.589/0.589/0.594/0.583/0.591。

全部在噪声内（n=37 / high=6）—— 本信号对阈值**不敏感**，
因为占比分布本来就宽（0.0~0.83 都有）。取 ``_LO=0.10``、``_HI=0.70``。

上限压到 0.6 的理由：真人提问也会打全称
（「雅诗兰黛小棕瓶多少钱」）。纯计数分不开「水军夸」和「真人问」，
所以不让它单独定性。要分清得配合正向词
（见 docs/NEW_SIGNALS_PROPOSAL.md 的 P3 计划）。
"""
from __future__ import annotations

from ..core.types import NoteRecord, SignalResult
from ._lexicon import BRAND_WORDS
from ._lib import clamp01
from .base import SignalContext, signal

NAME = "brand_mention_ratio"

#: 词表最短长度：单字词（「水」「霜」）会命中一切，噪声太大。
_MIN_WORD_LEN = 2

#: 占比低于 _LO 不起算，到 _HI 满格。
#: ⚠️ ``_HI`` 必须高于分布主体（p75=0.438），否则大半篇被压平。
_LO = 0.10
_HI = 0.70

#: 真人提问也会打全称，不让它单独定性。
_MAX_RISK = 0.6


@signal(NAME, group="text")
def compute(record: NoteRecord, *, ctx: SignalContext) -> SignalResult:
    # 词表 = 本篇 tags ∪ {跨语料词池里出现在本篇标题/正文的词}
    #
    # 后半句是兜底：tags 解析失败时（实测 7/43 篇）靠它认出品牌。
    # 例：tags=[] 但标题含「珂润面霜」→ 词表 = [珂润, 珂润面霜]。
    words = {t.strip() for t in record.tags
             if len(t.strip()) >= _MIN_WORD_LEN}
    text = record.text
    words |= {w for w in BRAND_WORDS if w in text}
    if not words:
        return SignalResult.missing_(
            NAME, "本篇没识别出品牌/产品词（tags 为空且正文未命中词池）"
            "—— 无法判断评论是否在念产品名")

    n = len(record.comments)
    if n < ctx.min_samples:
        return SignalResult.missing_(
            NAME, f"评论 {n} 条 < {ctx.min_samples}", n=n)

    hits = sum(1 for c in record.comments
               if any(w in c.content for w in words))
    ratio = hits / n

    risk = clamp01((ratio - _LO) / (_HI - _LO)) * _MAX_RISK
    return SignalResult.ok(
        NAME, risk, n=n,
        ratio=round(ratio, 3),
        hits=hits,
        # 记下词表规模 —— 调阈值时能看出是词表太窄还是真没提及
        words=len(words),
    )
