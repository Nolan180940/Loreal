"""发布后短时密集涌入 —— 水军派单刷量的时间指纹。

直觉
----
真实帖的评论是**跟着流量慢慢来**的：发布当天有几条，之后几天陆续有。
派单刷量是**集中在一小段时间内**灌进去的，因为任务有时限。

所以看的不是「跨度」（已有 ``comment_time_span``），而是
**评论相对发布时间的分布形态**：前 1 小时占了多大比例。

与 ``comment_time_span`` 的区别（两个信号都保留）
------------------------------------------------
==================  ==========================  ==========================
                    ``comment_time_span``       ``publish_burst``
==================  ==========================  ==========================
锚点                评论之间的跨度               **发布时间**
问的问题            「这一撮评论散不散」        「评论是不是挤在刚发布后」
能被首屏采样骗吗    **能**（前 5 条常集中）     **不能**（有绝对时间锚）
==================  ==========================  ==========================

第二条是关键：``comment_time_span`` 自己就承认「一条真实热帖的前 5 条
评论也可能集中在几分钟内」，因为匿名态只给首屏。但**发布后 1 小时
这个窗口是绝对的** —— 一条真实帖在发布后 1 小时内拿到 40% 的评论，
和一条刷量帖在发布后 1 小时内拿到 40% 的评论，前者要求帖子瞬间爆火
（罕见），后者只是任务按时交差（常见）。

实测（2026-10-11，40 篇标注里 37 篇可算，high 6 篇）
--------------------------------------------------
=========  ======  ========  ========  ======  ==========
窗口       形态      AUC       精确率    召回    误报
=========  ======  ========  ========  ======  ==========
5 分钟     比值     0.495      —         —       —
10 分钟    比值     0.495      —         —       —
30 分钟    比值     0.624      —         —       —
**60 分钟** 比值     **0.683**  —         —       —
180 分钟   比值     0.594      —         —       —
1440 分钟  比值     0.694      —         —       —
60 分钟    二元     0.739      0.31      0.83    11
=========  ======  ========  ========  ======  ==========

选 60 分钟 + 比值形态的理由：

- **10 分钟窗口没有区分度（0.495）** —— 但这不是「组员说错了」，
  是**我们的采样看不见**：匿名态每篇只给 5 条一级评论 + 楼中楼，
  十几条里要凑出「10 分钟内」很难。要验证 10 分钟得先有全量评论流。
- 60 分钟是比值形态的峰值，且正好是组员描述的窗口上界。
- **不用二元形态**：它 AUC 更高（0.739）但那是因为**零值之间互相并列**
  把 AUC 抬高了 —— 精确率只有 0.31（11 个误报）。
  比值保留了「有多猛」的次序，不会把 1 条和 5 条看成一样。

风险方向
--------
**1 小时内占比越高越可疑**。

阈值依据（扫出来的，不是拍的）
------------------------------
第一版我拍了个 ``_LO = 0.15``，结果 6 篇 high 里 4 篇的占比都低于它，
全被压成 risk=0 —— AUC 从 0.683 掉到 0.478。这正是代码库里记过的
「阈值落在分布之外导致信号恒 0」。扫描结果：

======  ======
_LO     AUC
======  ======
0.00    0.683
0.05    **0.685**
0.08    0.573
0.10    0.513
0.15    0.478  ← 第一版拍的
======  ======

所以 ``_LO`` 必须贴近 0 —— high 篇的占比散布在 0.00~0.43 整个区间。
``_HI`` 扫 0.25/0.35/0.50/0.70 分别得 0.683/0.691/0.685/0.685，取 0.35。

上限压到 0.7 的理由：精确率只有 0.31（真人也会在刚发布时涌进来），
不让它单独把人推向高风险。与 ``structure_markers`` 同档。
"""
from __future__ import annotations

from ..core.types import NoteRecord, SignalResult
from ._lib import clamp01
from .base import SignalContext, signal

NAME = "publish_burst"

#: 窗口：发布后多久算「短时」。见 docstring 的窗口扫描。
_WINDOW_MIN = 60.0

#: 占比低于 _LO 不起算，到 _HI 满格。**必须贴近 0**（见 docstring）。
_LO = 0.05
_HI = 0.35

#: 精确率只有 0.31，不让它单独定性。
_MAX_RISK = 0.7

#: 窗口扫描时记下的对照值，供以后复核（别删）。
_SWEEP = {5: 0.495, 10: 0.495, 30: 0.624, 60: 0.683,
          180: 0.594, 1440: 0.694}


@signal(NAME, group="comments")
def compute(record: NoteRecord, *, ctx: SignalContext) -> SignalResult:
    pub = record.published_ms
    if pub <= 0:
        return SignalResult.missing_(NAME, "笔记没有发布时间，无法算时间窗")

    ts = [c.time_ms for c in record.comments if c.time_ms > 0]
    n = len(ts)
    if n < ctx.min_samples:
        return SignalResult.missing_(
            NAME, f"有时间的评论 {n} 条 < {ctx.min_samples}", n=n)

    window_ms = _WINDOW_MIN * 60_000
    # 只数**发布之后**的评论。发布前的评论（改稿、置顶旧评）不算，
    # 也不能让它们把分母撑大 —— 那会稀释掉真正的爆发。
    after = [t for t in ts if t >= pub]
    if len(after) < ctx.min_samples:
        return SignalResult.missing_(
            NAME,
            f"发布后的评论只有 {len(after)} 条 < {ctx.min_samples}"
            "（其余评论时间早于发布时间，可能是置顶旧评）",
            n=len(after))

    in_window = sum(1 for t in after if t - pub <= window_ms)
    ratio = in_window / len(after)

    risk = clamp01((ratio - _LO) / (_HI - _LO)) * _MAX_RISK
    return SignalResult.ok(
        NAME, risk, n=len(after),
        ratio=round(ratio, 3),
        in_window=in_window,
        window_min=_WINDOW_MIN,
        # 顺带把 24h 占比记下来 —— 调阈值时不用重算
        ratio_24h=round(
            sum(1 for t in after if t - pub <= 86_400_000) / len(after), 3),
    )
